DROP TABLE TB_RA_RESERVA CASCADE CONSTRAINTS;
DROP TABLE TB_RA_NECESSIDADE CASCADE CONSTRAINTS;
DROP TABLE TB_RA_LOTE CASCADE CONSTRAINTS;
DROP TABLE TB_RA_ORGANIZACAO CASCADE CONSTRAINTS;

CREATE TABLE TB_RA_ORGANIZACAO (
    ID_ORGANIZACAO NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NM_ORGANIZACAO VARCHAR2(120) NOT NULL,
    TP_ORGANIZACAO VARCHAR2(15) NOT NULL,
    DS_ENDERECO    VARCHAR2(200) NOT NULL,
    DS_EMAIL       VARCHAR2(120) NOT NULL,
    CONSTRAINT CK_RA_ORG_TIPO CHECK (TP_ORGANIZACAO IN ('DOADOR', 'INSTITUICAO'))
);

CREATE TABLE TB_RA_LOTE (
    ID_LOTE          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_ORGANIZACAO   NUMBER NOT NULL,
    DS_CATEGORIA     VARCHAR2(40) NOT NULL,
    DS_LOTE          VARCHAR2(200) NOT NULL,
    NR_QUANTIDADE_KG NUMBER(10,2) NOT NULL,
    DT_VALIDADE      DATE NOT NULL,
    DS_CONSERVACAO   VARCHAR2(120) NOT NULL,
    DT_RETIRADA      DATE NOT NULL,
    ST_LOTE          VARCHAR2(15) DEFAULT 'DISPONIVEL' NOT NULL,
    CONSTRAINT FK_RA_LOTE_ORG FOREIGN KEY (ID_ORGANIZACAO) REFERENCES TB_RA_ORGANIZACAO (ID_ORGANIZACAO),
    CONSTRAINT CK_RA_LOTE_QTD CHECK (NR_QUANTIDADE_KG > 0),
    CONSTRAINT CK_RA_LOTE_ST CHECK (ST_LOTE IN ('DISPONIVEL', 'RESERVADO', 'ENTREGUE', 'CANCELADO'))
);

CREATE TABLE TB_RA_NECESSIDADE (
    ID_NECESSIDADE   NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_ORGANIZACAO   NUMBER NOT NULL,
    DS_CATEGORIA     VARCHAR2(40) NOT NULL,
    NR_QUANTIDADE_KG NUMBER(10,2) NOT NULL,
    ST_ATIVA         NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_RA_NEC_ORG FOREIGN KEY (ID_ORGANIZACAO) REFERENCES TB_RA_ORGANIZACAO (ID_ORGANIZACAO),
    CONSTRAINT CK_RA_NEC_QTD CHECK (NR_QUANTIDADE_KG > 0),
    CONSTRAINT CK_RA_NEC_ATIVA CHECK (ST_ATIVA IN (0, 1))
);

CREATE TABLE TB_RA_RESERVA (
    ID_RESERVA     NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_LOTE        NUMBER NOT NULL,
    ID_NECESSIDADE NUMBER NOT NULL,
    ST_RESERVA     VARCHAR2(15) DEFAULT 'AGENDADA' NOT NULL,
    DT_CRIACAO     DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_RA_RES_LOTE FOREIGN KEY (ID_LOTE) REFERENCES TB_RA_LOTE (ID_LOTE),
    CONSTRAINT FK_RA_RES_NEC FOREIGN KEY (ID_NECESSIDADE) REFERENCES TB_RA_NECESSIDADE (ID_NECESSIDADE),
    CONSTRAINT CK_RA_RES_ST CHECK (ST_RESERVA IN ('AGENDADA', 'COLETADA', 'ENTREGUE', 'CANCELADA'))
);

CREATE INDEX IDX_RA_LOTE_STATUS ON TB_RA_LOTE (ST_LOTE, DS_CATEGORIA);
CREATE INDEX IDX_RA_NEC_ATIVA ON TB_RA_NECESSIDADE (ST_ATIVA, DS_CATEGORIA);
CREATE INDEX IDX_RA_RES_LOTE ON TB_RA_RESERVA (ID_LOTE);

